export const toolPath = (id: string) =>
  id === 'application-ready'
    ? '/application-ready'
    : id === 'printdesk'
      ? '/printdesk'
      : '/tools/' + id
export const matchTools = (query: string) =>
  tools.filter((t) =>
    query
      .trim()
      .toLowerCase()
      .split(/\s+/)
      .every((word) =>
        [t.title, t.desc, t.category, t.aliases]
          .join(' ')
          .toLowerCase()
          .includes(word),
      ),
  )
